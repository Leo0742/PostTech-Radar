def _norm(value: str) -> str:
    return " ".join(value.lower().replace("ё", "е").split())


def _typos(text: str, rng: random.Random) -> str:
    replacements = [("не могу", "немогу"), ("приложение", "приложени"), ("отправление", "отправлние"), ("ошибка", "ошбика"), ("пожалуйста", "пожалуста")]
    for source, target in replacements:
        if rng.random() < 0.08:
            text = text.replace(source, target)
    if rng.random() < 0.18:
        text = text.replace(". ", " ", 1)
    return text


